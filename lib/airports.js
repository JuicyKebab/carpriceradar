// "ready" = live: surfaced in nav/home/hub and in the sitemap, indexable.
// "queued" = built (so pages exist and the price cron can warm data) but held
// back: noindex, not in the sitemap, not linked from nav/home/hub. Promote to
// "ready" in weekly batches of ~25-30 (staggered release indexes far better
// than dumping every page at once).
export const READY_AIRPORTS = AIRPORTS.filter((a) => a.status === "ready");
// Every airport that should get a statically-built page.
export const BUILT_AIRPORTS = AIRPORTS.filter(
  (a) => a.status === "ready" || a.status === "queued"
);

export function getAirport(slug) {
  return AIRPORTS.find((a) => a.slug === slug) || null;
}

